class UserAgentManager:
    """
    Manages user agent selection with configurable device type distribution.
    Returns both the user agent string and the device type for viewport matching.
    """

    def __init__(self, config: Dict):
        self.config = config
        devices = config.get("devices", {})
        self.desktop_pct = devices.get("desktop_percent", 55)
        self.mobile_pct = devices.get("mobile_percent", 40)
        # tablet_pct is the remainder

    def get_random(self) -> Tuple[str, str]:
        """
        Select a random user agent based on device distribution.
        
        Returns:
            Tuple of (user_agent_string, device_type)
        """
        roll = random.randint(1, 100)

        if roll <= self.desktop_pct:
            return random.choice(DESKTOP_USER_AGENTS), "desktop"
        elif roll <= self.desktop_pct + self.mobile_pct:
            return random.choice(MOBILE_USER_AGENTS), "mobile"
        else:
            return random.choice(TABLET_USER_AGENTS), "tablet"

    def get_desktop(self) -> str:
        """Get a random desktop user agent."""
        return random.choice(DESKTOP_USER_AGENTS)

    def get_mobile(self) -> str:
        """Get a random mobile user agent."""
        return random.choice(MOBILE_USER_AGENTS)

    def get_tablet(self) -> str:
        """Get a random tablet user agent."""
        return random.choice(TABLET_USER_AGENTS)
